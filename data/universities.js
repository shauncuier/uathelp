function slugify(name) {
  return name
    .toLowerCase()
    .replace(/&/g, "and")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
}

function normalizeWebsite(website) {
  if (!website) return "https://ugc.gov.bd";
  return website.startsWith("http") ? website : `https://${website}`;
}

function buildRecord(entry, index, defaultType) {
  const [name, location, website, explicitType] = entry;
  const type = explicitType || defaultType;
  const isMedical = type === "medical";
  const isEngineering = type === "engineering";
  const establishedYear = isMedical ? 2000 : isEngineering ? 2003 : type === "private" ? 2001 : 1995;

  return {
    id: String(index + 1),
    name,
    slug: slugify(name),
    type,
    location,
    description: `${name} is a ${type} institution in Bangladesh.`,
    website: normalizeWebsite(website),
    minGpa: isMedical || isEngineering ? 5.0 : type === "private" ? 2.5 : 3.5,
    seatCount: isMedical ? 100 : isEngineering ? 900 : type === "private" ? 3000 : 2500,
    establishedYear,
    ranking: index + 1,
    isFeatured: index < 12,
    programs: DEFAULT_PROGRAMS[type],
    admissionDeadline: DEFAULT_DEADLINES[type],
    examDate: isMedical ? "2026-12-01" : isEngineering ? "2026-11-01" : undefined,
  };
}

